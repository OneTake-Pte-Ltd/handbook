// Joins edge/src/main.js and every module it imports into one file,
// edge/dist/edge.mjs, because a Bunny edge script is a single file.
//
// No bundler: this script relies on three conventions in edge/src.
//   1. Local imports are named imports on their own: import { a, b } from "./x.js";
//   2. Exports are written inline: export function / export const / export class.
//   3. Top-level names are unique across all modules (the build checks this).
// Imports of "npm:" and "node:" packages are kept and moved to the top.
//
// Usage: node edge/build.mjs

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const entry = join(root, "src", "main.js");
const outFile = join(root, "dist", "edge.mjs");

const LOCAL_IMPORT = /^import\s*\{([^}]*)\}\s*from\s*["'](\.{1,2}\/[^"']+)["'];?[ \t]*$/gm;
const PACKAGE_IMPORT = /^import\s[^;]*?from\s*["']((?:npm|node|jsr):[^"']+)["'];?[ \t]*$/gm;
const ANY_IMPORT = /^import\s/m;
const EXPORT_DECL = /^export\s+(?=(async\s+)?function\b|const\b|let\b|class\b)/gm;
const FORBIDDEN_EXPORT = /^export\s+(default\b|\{|\*)/m;
const TOP_LEVEL_NAME = /^(?:async\s+)?(?:function\*?|const|let|class)\s+([A-Za-z_$][\w$]*)/gm;

function fail(message) {
  console.error(`edge build failed: ${message}`);
  process.exit(1);
}

const ordered = [];
const visiting = new Set();
const done = new Set();
const packageImports = new Set();

function visit(file) {
  if (done.has(file)) return;
  if (visiting.has(file)) fail(`circular import involving ${relative(root, file)}`);
  visiting.add(file);
  let code = readFileSync(file, "utf8");
  const deps = [];

  code = code.replace(PACKAGE_IMPORT, (line) => {
    packageImports.add(line.trim().replace(/;?$/, ";"));
    return "";
  });
  code = code.replace(LOCAL_IMPORT, (_line, _names, spec) => {
    deps.push(resolve(dirname(file), spec));
    return "";
  });
  if (ANY_IMPORT.test(code)) {
    fail(`${relative(root, file)} has an import the build does not understand. Use: import { name } from "./file.js";`);
  }
  if (FORBIDDEN_EXPORT.test(code)) {
    fail(`${relative(root, file)} uses export default, export { } or export *. Write exports inline instead.`);
  }
  code = code.replace(EXPORT_DECL, "");

  for (const dep of deps) visit(dep);
  visiting.delete(file);
  done.add(file);
  ordered.push({ file, code });
}

visit(entry);

// Check that no two modules declare the same top-level name.
const owners = new Map();
for (const { file, code } of ordered) {
  for (const match of code.matchAll(TOP_LEVEL_NAME)) {
    const name = match[1];
    if (owners.has(name) && owners.get(name) !== file) {
      fail(`"${name}" is declared in both ${relative(root, owners.get(name))} and ${relative(root, file)}`);
    }
    owners.set(name, file);
  }
}

let commit = "";
try {
  commit = execFileSync("git", ["rev-parse", "--short", "HEAD"], { cwd: root, encoding: "utf8" }).trim();
} catch {
  commit = "unknown";
}

const parts = [
  `// Handbook edge script, built from edge/src (commit ${commit}).`,
  "// Do not edit this file: edit edge/src and run node edge/build.mjs.",
  "",
  ...packageImports,
  "",
  ...ordered.map(({ file, code }) => `// ---- ${relative(root, file)}\n${code.trim()}\n`),
];

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, parts.join("\n"));

// Syntax check of the joined file (duplicate declarations are syntax errors too).
try {
  execFileSync(process.execPath, ["--check", outFile], { stdio: "pipe" });
} catch (error) {
  fail(`the joined file does not parse:\n${error.stderr}`);
}

console.log(`Built ${relative(process.cwd(), outFile)} from ${ordered.length} modules.`);
